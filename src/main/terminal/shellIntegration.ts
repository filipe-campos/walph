import { basename, join } from 'node:path'

export interface ShellLaunch {
  file: string
  args: string[]
  env: Record<string, string>
}

type ShellKind = 'zsh' | 'bash'

const ZSH_FILES = ['.zshenv', '.zprofile', '.zshrc', '.zlogin'] as const

// Colors by ANSI index (not hex): the prompt follows the xterm light/dark theme. ❯ in ansi-magenta (design system),
// red after a failed command; folder in ansi-blue; user@host in ansi-bright-black.
const ZSH_PROMPT = "'%F{8}%n@%m%f %F{blue}%1~%f %(?.%F{magenta}.%F{red})❯%f '"
const BASH_PROMPT =
  "'\\[\\e[90m\\]\\u@\\h\\[\\e[0m\\] \\[\\e[34m\\]\\W\\[\\e[0m\\] \\[\\e[$(( $? ? 31 : 35 ))m\\]❯\\[\\e[0m\\] '"

// Stock prompts: plain zsh, macOS /etc/zshrc; plain bash, macOS /etc/bashrc and the Debian/Ubuntu ~/.bashrc.
const ZSH_DEFAULT_PROMPTS = ["'%m%# '", "'%n@%m %1~ %# '"]
const BASH_DEFAULT_PROMPTS = [
  "'\\s-\\v\\$ '",
  "'\\h:\\W \\u\\$ '",
  "'\\u@\\h:\\w\\$ '",
  "'${debian_chroot:+($debian_chroot)}\\u@\\h:\\w\\$ '"
]

function shellKind(launch: ShellLaunch, platform: string): ShellKind | null {
  if (platform === 'win32') return null
  const name = basename(launch.file)
  if (name !== 'zsh' && name !== 'bash') return null
  // Custom arguments (profile) may already carry `-c`, `--rcfile` etc.: only the default invocation is touched.
  if (launch.args.length > 1 || (launch.args.length === 1 && launch.args[0] !== '-l')) return null
  return name
}

/** Points zsh/bash to the scripts in `dir`, which load the user's files and only then color the default prompt. */
export function withShellIntegration(launch: ShellLaunch, platform: string, dir: string): ShellLaunch {
  const kind = shellKind(launch, platform)
  if (kind === 'zsh') {
    const zdotdir = join(dir, 'zsh')
    const env = {
      ...launch.env,
      ZDOTDIR: zdotdir,
      WALPH_ZDOTDIR: zdotdir,
      WALPH_USER_ZDOTDIR: launch.env.ZDOTDIR ?? ''
    }
    return { ...launch, env }
  }
  if (kind === 'bash') {
    // `--init-file` only applies outside login mode: the script loads the login profiles itself.
    const env = { ...launch.env, WALPH_BASH_LOGIN: launch.args.includes('-l') ? '1' : '' }
    return { ...launch, args: ['--init-file', join(dir, 'bash', 'init.bash')], env }
  }
  return launch
}

function zshFile(name: (typeof ZSH_FILES)[number]): string {
  const lines = [
    '# Generated by Walph on every start; edits are lost.',
    'ZDOTDIR=${WALPH_USER_ZDOTDIR:-$HOME}',
    // The macOS /etc/zshrc writes the history to $ZDOTDIR, which up to here was the Walph folder.
    ...(name === '.zshrc' ? ['[[ $HISTFILE == $WALPH_ZDOTDIR/.zsh_history ]] && HISTFILE=$ZDOTDIR/.zsh_history'] : []),
    `[[ -r $ZDOTDIR/${name} ]] && builtin source $ZDOTDIR/${name}`,
    'WALPH_USER_ZDOTDIR=$ZDOTDIR',
    'ZDOTDIR=$WALPH_ZDOTDIR'
  ]
  if (name === '.zshrc') {
    lines.push(
      `if [[ ${ZSH_DEFAULT_PROMPTS.map((p) => `$PROMPT == ${p}`).join(' || ')} ]]; then`,
      `  PROMPT=${ZSH_PROMPT}`,
      'fi'
    )
  }
  // The last file read (`.zlogin` on login, `.zshrc` otherwise) restores the user's ZDOTDIR.
  const restore = name === '.zlogin' ? '' : name === '.zshrc' ? '[[ -o login ]] || ' : null
  if (restore !== null) {
    lines.push(
      `${restore}{`,
      '  if [[ $WALPH_USER_ZDOTDIR == $HOME ]]; then unset ZDOTDIR; else ZDOTDIR=$WALPH_USER_ZDOTDIR; fi',
      '  unset WALPH_ZDOTDIR WALPH_USER_ZDOTDIR',
      '}'
    )
  }
  return lines.join('\n') + '\n'
}

function bashInit(): string {
  return [
    '# Generated by Walph on every start; edits are lost.',
    'if [[ -n $WALPH_BASH_LOGIN ]]; then',
    '  [[ -r /etc/profile ]] && builtin source /etc/profile',
    '  for __walph_f in ~/.bash_profile ~/.bash_login ~/.profile; do',
    '    if [[ -r $__walph_f ]]; then builtin source "$__walph_f"; break; fi',
    '  done',
    '  unset __walph_f',
    'else',
    '  [[ -r ~/.bashrc ]] && builtin source ~/.bashrc',
    'fi',
    'case $PS1 in',
    `  ${BASH_DEFAULT_PROMPTS.join(' | ')}) PS1=${BASH_PROMPT} ;;`,
    'esac',
    'unset WALPH_BASH_LOGIN',
    ''
  ].join('\n')
}

/** Files (path relative to the integration folder → content) that `withShellIntegration` expects to find. */
export function shellIntegrationFiles(): Record<string, string> {
  const files: Record<string, string> = { [join('bash', 'init.bash')]: bashInit() }
  for (const name of ZSH_FILES) files[join('zsh', name)] = zshFile(name)
  return files
}
